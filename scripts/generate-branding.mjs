/**
 * Emit the frontend's branding module from `branding.toml`.
 *
 * A browser cannot read TOML, and the alternative — fetching the config before
 * the window can title itself — puts a request in front of the first frame of
 * every surface that says the product's name. So the strings are compiled in,
 * the same way the Rust side compiles them in, and both are committed at the
 * same moment by the same file.
 *
 * One module per frontend bundle rather than one shared module, because
 * STANDARDS.md §1.4 says an app reaches its host through `@veistra/bridge` and
 * nothing else. A generated file inside the app's own source tree is the only
 * form that survives that app being extracted to its own repository, which
 * `apps/README.md` says is the point of the boundary.
 *
 * All three are gitignored. `branding.toml` is the source of truth; editing the
 * output is pointless, because the next `pnpm typecheck` overwrites it.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { readBranding, repoRoot } from "./read-branding.mjs";

/** Every bundle that draws a brand string. Tutorial is here because its mocks
 *  draw the title bar caption, which is a depiction of a surface and so has to
 *  agree with it — see `docs/branding.md` §7. */
const OUTPUTS = [
  "src/branding.generated.ts",
  "apps/home/ui/src/branding.generated.ts",
  "apps/files/ui/src/branding.generated.ts",
  "apps/tutorial/ui/src/branding.generated.ts",
];

const VIEW_BOX = /\bviewBox="([^"]+)"/;
const PATH_D = /<path\b[^>]*\bd="([^"]+)"/;
const DRAWABLE = /<(path|circle|ellipse|rect|line|polyline|polygon|text|image|use)\b/g;

/**
 * Reduce the mark to a `viewBox` and one path.
 *
 * The shell draws the mark as inline SVG in `currentColor` — it sits on the
 * title bar at 15px and again as the placeholder every tool shares — so it
 * needs the geometry, not a file. An `<img>` cannot inherit the text colour,
 * and a mask would move the colour decision to each call site.
 *
 * A mark this cannot reduce is a hard failure rather than a partial draw: half
 * a logo rendered silently is worse than a build that says which file to fix.
 */
function markFrom(path, declared) {
  const svg = readFileSync(path, "utf8");
  const drawables = svg.match(DRAWABLE) ?? [];
  if (drawables.length !== 1 || !drawables[0].startsWith("<path")) {
    throw new Error(
      `${declared}: the mark must be exactly one <path>, found ${drawables.length || "none"} ` +
        `(${drawables.join(" ") || "no drawable elements"}). ` +
        `A mark that cannot be one path belongs on a surface that loads it as a file.`,
    );
  }
  const viewBox = VIEW_BOX.exec(svg);
  const d = PATH_D.exec(svg);
  if (!viewBox) throw new Error(`${declared}: no viewBox — the mark has to scale`);
  if (!d) throw new Error(`${declared}: the <path> has no d attribute`);
  return { viewBox: viewBox[1], d: d[1] };
}

function render({ product, mark }) {
  const s = (value) => JSON.stringify(value);
  return `/**
 * GENERATED by scripts/generate-branding.mjs from branding.toml, and gitignored.
 * Every interface surface that names the product reads it from here; see
 * docs/branding.md for the full list and for what must never be renamed.
 */

/** The product's name, as written in prose, window titles and menus. */
export const PRODUCT_NAME = ${s(product.name)};

/** The wordmark's text node, in mixed case. The stylesheet uppercases it. */
export const WORDMARK = ${s(product.wordmark)};

/** The line under the lockup on Home's hero. */
export const TAGLINE = ${s(product.tagline)};

/** The mark's outline, lifted from the SVG \`[assets] mark\` names. */
export const MARK_PATH = ${s(mark.d)};

/** That path's coordinate box, so a replacement mark need not be 24x24. */
export const MARK_VIEW_BOX = ${s(mark.viewBox)};
`;
}

const { product, assetPaths } = readBranding();
const mark = markFrom(assetPaths.mark.absolute, assetPaths.mark.declared);
const source = render({ product, mark });

for (const out of OUTPUTS) writeFileSync(join(repoRoot, out), source, "utf8");

console.log(`branding: ${product.name} -> ${OUTPUTS.length} modules`);
