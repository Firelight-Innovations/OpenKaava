/** An older adapter can still offer legacy builtins without misclassifying them as skills. */
const legacy = new Set(["pr-comments", "ultraplan", "vim"]);

export function builtins(harness: Harness): readonly AgentCommand[] {
  return harness === "codex" ? codex : claude;
}

/** Never infer builtins from punctuation alone: plugin names and custom commands are skills. */
export function isSkillCommand(command: AgentCommand, harness: Harness): boolean {
  if (command.name.startsWith("$")) return true;
  if (harness === "claude" && claudeSkills.has(command.name)) return true;
  return (
    !builtins(harness).some((entry) => entry.name === command.name) &&
    !(harness === "claude" && legacy.has(command.name))
  );
}
